package dev.galacticraft.api.rocket.part.data;

import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import io.netty.buffer.ByteBuf;
import net.minecraft.network.codec.ByteBufCodecs;
import net.minecraft.network.codec.StreamCodec;
import org.jetbrains.annotations.Contract;
import org.jetbrains.annotations.NotNull;

/**
 * Immutable physical and environmental attributes of a rocket part.
 *
 * @param thrustKn               Propulsive thrust generated by the part in kilonewtons (kN). 0.0 for passive parts.
 * @param dryWeightKg            Dry structural mass in kilograms (kg).
 * @param fuelCapacityDroplets   Propellant storage volume in Fabric Transfer API droplets (81,000 droplets = 1 bucket = 1,000 mB).
 * @param pressureToleranceAtm   Maximum external ambient pressure in atmospheres (atm/bar) before structural collapse.
 * @param thermalToleranceKelvin Maximum operational stagnation temperature in Kelvin (K) before thermal failure.
 */
public record RocketPartStats(
        double thrustKn,
        double dryWeightKg,
        long fuelCapacityDroplets,
        double pressureToleranceAtm,
        double thermalToleranceKelvin
) {
    /**
     * Compact canonical constructor enforcing defensive non-negative physical bounds and NaN sanitization.
     */
    public RocketPartStats {
        thrustKn = Double.isNaN(thrustKn) ? 0.0 : Math.max(0.0, thrustKn);
        dryWeightKg = Double.isNaN(dryWeightKg) ? 0.0 : Math.max(0.0, dryWeightKg);
        fuelCapacityDroplets = Math.max(0L, fuelCapacityDroplets);
        pressureToleranceAtm = Double.isNaN(pressureToleranceAtm) ? 0.0 : Math.max(0.0, pressureToleranceAtm);
        thermalToleranceKelvin = Double.isNaN(thermalToleranceKelvin) ? 0.0 : Math.max(0.0, thermalToleranceKelvin);
    }

    /**
     * Default baseline instance representing a passive structural component under standard terrestrial conditions.
     * Ambient pressure is 1.0 atm (sea level); ambient temperature is 300.0 K (~27°C).
     */
    public static final RocketPartStats ZERO = new RocketPartStats(0.0, 0.0, 0L, 1.0, 300.0);

    /**
     * Mojang Codec for NBT persistence and JSON recipe data serialization.
     */
    public static final Codec<RocketPartStats> CODEC = RecordCodecBuilder.create(instance -> instance.group(
            Codec.DOUBLE.fieldOf("thrust_kn").forGetter(RocketPartStats::thrustKn),
            Codec.DOUBLE.fieldOf("dry_weight_kg").forGetter(RocketPartStats::dryWeightKg),
            Codec.LONG.fieldOf("fuel_capacity_droplets").forGetter(RocketPartStats::fuelCapacityDroplets),
            Codec.DOUBLE.fieldOf("pressure_tolerance_atm").forGetter(RocketPartStats::pressureToleranceAtm),
            Codec.DOUBLE.fieldOf("thermal_tolerance_kelvin").forGetter(RocketPartStats::thermalToleranceKelvin)
    ).apply(instance, RocketPartStats::new));

    /**
     * High-performance network binary stream codec.
     * Serializes doubles as 64-bit IEEE floats and fuel droplets as compact VarLongs.
     */
    public static final StreamCodec<ByteBuf, RocketPartStats> STREAM_CODEC = StreamCodec.composite(
            ByteBufCodecs.DOUBLE, RocketPartStats::thrustKn,
            ByteBufCodecs.DOUBLE, RocketPartStats::dryWeightKg,
            ByteBufCodecs.VAR_LONG, RocketPartStats::fuelCapacityDroplets,
            ByteBufCodecs.DOUBLE, RocketPartStats::pressureToleranceAtm,
            ByteBufCodecs.DOUBLE, RocketPartStats::thermalToleranceKelvin,
            RocketPartStats::new
    );

    @Contract("-> new")
    public static @NotNull Builder builder() {
        return new Builder();
    }

    public @NotNull RocketPartStats withThrust(double thrustKn) {
        return new RocketPartStats(thrustKn, this.dryWeightKg, this.fuelCapacityDroplets, this.pressureToleranceAtm, this.thermalToleranceKelvin);
    }

    public @NotNull RocketPartStats withDryWeight(double dryWeightKg) {
        return new RocketPartStats(this.thrustKn, dryWeightKg, this.fuelCapacityDroplets, this.pressureToleranceAtm, this.thermalToleranceKelvin);
    }

    public @NotNull RocketPartStats withFuelCapacity(long fuelCapacityDroplets) {
        return new RocketPartStats(this.thrustKn, this.dryWeightKg, fuelCapacityDroplets, this.pressureToleranceAtm, this.thermalToleranceKelvin);
    }

    public @NotNull RocketPartStats withPressureTolerance(double pressureToleranceAtm) {
        return new RocketPartStats(this.thrustKn, this.dryWeightKg, this.fuelCapacityDroplets, pressureToleranceAtm, this.thermalToleranceKelvin);
    }

    public @NotNull RocketPartStats withThermalTolerance(double thermalToleranceKelvin) {
        return new RocketPartStats(this.thrustKn, this.dryWeightKg, this.fuelCapacityDroplets, this.pressureToleranceAtm, thermalToleranceKelvin);
    }

    /**
     * Fluent builder for programmatic construction in recipes, prefabs, and test suites.
     */
    public static final class Builder {
        private double thrustKn = 0.0;
        private double dryWeightKg = 0.0;
        private long fuelCapacityDroplets = 0L;
        private double pressureToleranceAtm = 1.0;
        private double thermalToleranceKelvin = 300.0;

        private Builder() {}

        public Builder thrust(double thrustKn) {
            this.thrustKn = thrustKn;
            return this;
        }

        public Builder dryWeight(double dryWeightKg) {
            this.dryWeightKg = dryWeightKg;
            return this;
        }

        public Builder fuelCapacity(long fuelCapacityDroplets) {
            this.fuelCapacityDroplets = fuelCapacityDroplets;
            return this;
        }

        public Builder fuelBuckets(double buckets) {
            if (Double.isNaN(buckets) || buckets <= 0.0) {
                this.fuelCapacityDroplets = 0L;
            } else {
                this.fuelCapacityDroplets = (long) Math.min((double) Long.MAX_VALUE, buckets * 81000.0);
            }
            return this;
        }

        public Builder pressureTolerance(double pressureToleranceAtm) {
            this.pressureToleranceAtm = pressureToleranceAtm;
            return this;
        }

        public Builder thermalTolerance(double thermalToleranceKelvin) {
            this.thermalToleranceKelvin = thermalToleranceKelvin;
            return this;
        }

        public RocketPartStats build() {
            return new RocketPartStats(
                    this.thrustKn,
                    this.dryWeightKg,
                    this.fuelCapacityDroplets,
                    this.pressureToleranceAtm,
                    this.thermalToleranceKelvin
            );
        }
    }
}
