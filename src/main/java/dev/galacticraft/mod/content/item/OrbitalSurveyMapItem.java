package dev.galacticraft.mod.content.item;

import dev.galacticraft.api.component.GCDataComponents;
import dev.galacticraft.api.component.OrbitalSurveyData;
import net.minecraft.ChatFormatting;
import net.minecraft.network.chat.Component;
import net.minecraft.world.InteractionHand;
import net.minecraft.world.InteractionResultHolder;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.TooltipFlag;
import net.minecraft.world.level.Level;
import org.jetbrains.annotations.NotNull;

import java.util.List;

/**
 * Multispectral orbital cartography chart ({@code ORBITAL_SURVEY_MAP}) generated by
 * {@code science_orbital_camera_multispectral}. Displays real mineral deposit coordinates,
 * biome identification, and detected {@code CRASHED_PROBE} coordinates.
 */
public class OrbitalSurveyMapItem extends Item {
    public OrbitalSurveyMapItem(Properties properties) {
        super(properties);
    }

    @Override
    public @NotNull InteractionResultHolder<ItemStack> use(Level level, Player player, InteractionHand hand) {
        ItemStack stack = player.getItemInHand(hand);
        if (!level.isClientSide) {
            OrbitalSurveyData data = stack.get(GCDataComponents.ORBITAL_SURVEY_DATA);
            if (data == null) {
                player.displayClientMessage(Component.literal("[ORBITAL SURVEY] No multispectral scan recorded.").withStyle(ChatFormatting.GRAY), true);
            } else {
                player.sendSystemMessage(Component.literal("=== ORBITAL SURVEY: " + data.planetName() + " ===").withStyle(ChatFormatting.AQUA, ChatFormatting.BOLD));
                player.sendSystemMessage(Component.literal("  Ore Hotspot (" + data.oreLabel() + "): X=" + data.oreHotspotX()
                        + ", Y=" + data.oreHotspotY() + ", Z=" + data.oreHotspotZ()).withStyle(ChatFormatting.GREEN));
                player.sendSystemMessage(Component.literal("  Surveyed Biome: " + data.biomeName()).withStyle(ChatFormatting.YELLOW));
                if (data.probeDetected()) {
                    player.sendSystemMessage(Component.literal("  Crashed Probe Signal: X=" + data.probeX() + ", Z=" + data.probeZ()).withStyle(ChatFormatting.LIGHT_PURPLE));
                } else {
                    player.sendSystemMessage(Component.literal("  Crashed Probe Signal: None within orbital swath").withStyle(ChatFormatting.DARK_GRAY));
                }
            }
        }
        return InteractionResultHolder.sidedSuccess(stack, level.isClientSide);
    }

    @Override
    public void appendHoverText(ItemStack stack, TooltipContext context, List<Component> tooltip, TooltipFlag flag) {
        super.appendHoverText(stack, context, tooltip, flag);
        OrbitalSurveyData data = stack.get(GCDataComponents.ORBITAL_SURVEY_DATA);
        if (data == null) {
            tooltip.add(Component.literal("Uncalibrated orbital survey sheet").withStyle(ChatFormatting.DARK_GRAY));
            return;
        }
        tooltip.add(Component.literal("Body: " + data.planetName()).withStyle(ChatFormatting.AQUA));
        tooltip.add(Component.literal("Ore Deposit: " + data.oreLabel() + " @ "
                + data.oreHotspotX() + ", " + data.oreHotspotY() + ", " + data.oreHotspotZ()).withStyle(ChatFormatting.GREEN));
        tooltip.add(Component.literal("Biome: " + data.biomeName()).withStyle(ChatFormatting.YELLOW));
        if (data.probeDetected()) {
            tooltip.add(Component.literal("Crashed Probe: X=" + data.probeX() + ", Z=" + data.probeZ()).withStyle(ChatFormatting.LIGHT_PURPLE));
        }
        tooltip.add(Component.literal("Right-click to print coordinates to mission log").withStyle(ChatFormatting.DARK_GRAY));
    }
}
