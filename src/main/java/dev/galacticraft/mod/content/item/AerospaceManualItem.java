package dev.galacticraft.mod.content.item;

import dev.galacticraft.mod.manual.ManualClientBridge;
import net.minecraft.ChatFormatting;
import net.minecraft.network.chat.Component;
import net.minecraft.sounds.SoundEvents;
import net.minecraft.world.InteractionHand;
import net.minecraft.world.InteractionResultHolder;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.TooltipFlag;
import net.minecraft.world.level.Level;
import org.jetbrains.annotations.NotNull;

import java.util.List;

/**
 * Physical item for the interactive, progressive Galacticraft 5 Aerospace Manual ({@code AEROSPACE_MANUAL}).
 * Opens the client-side {@code AerospaceManualScreen} with zero menu/packet overhead.
 */
public class AerospaceManualItem extends Item {
    public AerospaceManualItem(Properties properties) {
        super(properties);
    }

    @Override
    public @NotNull InteractionResultHolder<ItemStack> use(@NotNull Level level, @NotNull Player player, @NotNull InteractionHand hand) {
        ItemStack stack = player.getItemInHand(hand);
        if (level.isClientSide) {
            player.playSound(SoundEvents.BOOK_PAGE_TURN, 0.85F, 1.05F);
            ManualClientBridge.openManual(null);
        }
        return InteractionResultHolder.sidedSuccess(stack, level.isClientSide);
    }

    @Override
    public void appendHoverText(@NotNull ItemStack stack, @NotNull TooltipContext context, @NotNull List<Component> tooltip, @NotNull TooltipFlag flag) {
        tooltip.add(Component.translatable("item.galacticraft.aerospace_manual.desc1").withStyle(ChatFormatting.AQUA));
        tooltip.add(Component.translatable("item.galacticraft.aerospace_manual.desc2").withStyle(ChatFormatting.GRAY));
    }
}
